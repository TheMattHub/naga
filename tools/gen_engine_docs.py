# -- the digital-twin page's list of what a twin cannot start from ---------------------------

STATE_LIMITS_BEGIN = "<!-- state-limits:begin -->"
STATE_LIMITS_END = "<!-- state-limits:end -->"
LIMITS_PAGE = DOCS / "digital-twin.md"


def state_limit_kinds() -> list[str]:
    """The kinds `nagasim/state.py` refuses with `_unsupported(kind, ...)`, in source order. A kind
    is a string literal passed directly, or the first item of a `(kind, found)` pair in the loop
    that passes a variable. A kind with a name in it (an f-string) is left out."""
    import ast

    tree = ast.parse((ROOT / "nagasim" / "state.py").read_text(encoding="utf-8"))
    kinds: list[str] = []

    def add(node) -> None:
        if isinstance(node, ast.Constant) and isinstance(node.value, str) and node.value not in kinds:
            kinds.append(node.value)

    for func in ast.walk(tree):
        if not isinstance(func, ast.FunctionDef):
            continue
        calls = [n for n in ast.walk(func) if isinstance(n, ast.Call) and getattr(n.func, "id", "") == "_unsupported"]
        for call in calls:
            add(call.args[0])
        if any(isinstance(call.args[0], ast.Name) for call in calls):
            for loop in (n for n in ast.walk(func) if isinstance(n, ast.For)):
                for pair in ast.walk(loop.iter):
                    if isinstance(pair, ast.Tuple) and len(pair.elts) == 2:
                        add(pair.elts[0])
    return kinds


def state_limits_text() -> str:
    kinds = state_limit_kinds()
    return "\n".join((
        "A twin cannot yet start from a state that carries any of the following. Such a model is still",
        "monitored, and the state or forecast that needs it is refused by name, never started partly.",
        "", *(f"- {kind}" for kind in kinds), "",
        "The list is the one the engine's own refusals use, so it is as long as the engine's limits."))


def gen_limits() -> None:
    path = LIMITS_PAGE
    text = path.read_text(encoding="utf-8")
    head, rest = text.split(STATE_LIMITS_BEGIN)
    _old, tail = rest.split(STATE_LIMITS_END)
    block = "\n".join((STATE_LIMITS_BEGIN, state_limits_text(), STATE_LIMITS_END))
    path.write_text(head + block + tail, encoding="utf-8", newline="\n")


