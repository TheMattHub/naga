# ------------------------------------------------------------- build.pyi
#
# `nagasim.build` makes its methods at attribute access; this stub tells an editor (and a
# type checker) what they are, from the same registries and the same JSON Schema
# (`tests/test_build.py` compares). Plugins are run-time only: they are not here.

STUB = ROOT / "nagasim" / "build.pyi"
_JSON_PY = {"number": "float", "integer": "int", "boolean": "bool", "string": "str",
            "null": "None", "array": "list[Any]", "object": "dict[str, Any]"}
# A distribution parameter's DistParam.kind; a number may be an expression too.
_DIST_KINDS = {"number": "float | str", "list": "list[Any]", "expression": "str"}


def _py_type(schema, defs: dict, depth: int = 0) -> str:
    """The Python annotation for a JSON Schema: refs followed, unions joined, else Any."""
    if not isinstance(schema, dict) or depth > 4:
        return "Any"
    ref = schema.get("$ref", "").rsplit("/", 1)[-1]
    if ref == "duration":
        return "Distribution | dict[str, Any]"
    if ref:
        return _py_type(defs.get(ref), defs, depth + 1)
    if "const" in schema:
        return _JSON_PY.get({str: "string", bool: "boolean", int: "integer",
                             float: "number"}.get(type(schema["const"]), ""), "Any")
    members = schema.get("anyOf") or schema.get("oneOf")
    if members:
        kinds = [_py_type(m, defs, depth + 1) for m in members]
    elif "type" in schema:
        kinds = [_JSON_PY.get(t, "Any") for t in
                 ([schema["type"]] if isinstance(schema["type"], str) else schema["type"])]
    elif "enum" in schema and all(isinstance(v, str) for v in schema["enum"]):
        kinds = ["str"]
    else:
        return "Any"
    parts = list(dict.fromkeys(p for kind in kinds for p in kind.split(" | ")))
    return "Any" if "Any" in parts else " | ".join(parts)


def _default(value) -> str:
    """A default a stub can hold: a short literal, else `...`."""
    if value is None or isinstance(value, (bool, int, str)) or (
            isinstance(value, float) and value == value and abs(value) != float("inf")):
        text = repr(value)
        return text if len(text) <= 40 else "..."
    return "..."


def _docstring(lines: list[str], indent: str) -> list[str]:
    text = "\n".join(lines).strip().replace("\\", "\\\\").replace('"""', '\\"\\"\\"')
    body = [f"{indent}{line}".rstrip() for line in text.split("\n")]
    body[0] = f'{indent}"""{body[0].lstrip()}'
    return body + [f'{indent}"""']


def _signature(name: str, params: list[str], returns: str, doc: list[str], self_: bool = True,
               indent: str = "    ") -> list[str]:
    head = (["self"] if self_ else []) + params
    one = f"{indent}def {name}({', '.join(head)}) -> {returns}:"
    lines = [one] if len(one) <= 100 else (
        [f"{indent}def {name}("] + [f"{indent}    {p}," for p in head] + [f"{indent}) -> {returns}:"])
    return lines + _docstring(doc, indent + "    ")


def _unit_kind(kind: str, quantity: str, base: bool = True) -> str:
    """*kind* with its `str` narrowed to the units the engine accepts for *quantity*, so an
    editor completes a unit keyword and flags a wrong one (D480). Speed is any length/time."""
    choices = ([f"{a}/{b}" for a in LENGTH_ABBR.values() for b in TIME_ABBR.values()]
               if quantity == "speed" else list(unit_choices(quantity)))
    literal = "Literal[" + ", ".join(repr(c) for c in (["base"] if base else []) + choices) + "]"
    return " | ".join(literal if part == "str" else part for part in kind.split(" | "))


def _units_of(params) -> dict[str, str]:
    """{unit keyword: quantity} of a list of ParamSpecs."""
    return {p.unit_field: p.quantity for p in params if p.unit_field}


