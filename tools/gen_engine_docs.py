# A code from the project's own plans ("PHASE6 A8", "D345", "6D1 U3"): it means nothing to a reader.
# tests/test_engine_docs.py scans both sites for it.
PLAN_CODE = re.compile(r"PHASE ?\d|ARCH-REVIEW|ARCHITECTURE [\dD]|DEVLOG|ROADMAP|\b\d[A-Z]\d? [A-Z]\d\b|\bD\d{2,4}\b"
                       r"|(?<![\w&/])#\d{3,4}\b(?![\w-])")
_PAREN = re.compile(r"[ \t]*\(([^()]*)\)", re.S)


def without_plan_codes(text: str) -> str:
    """*text* without the parentheticals that cite a plan code: the product's reference copies
    text written for the maintainers (asset help, the migration table). The sentence reads on
    without the parenthesis; a bare code outside one is left, and the docs test reports it."""
    return _PAREN.sub(lambda m: "" if PLAN_CODE.search(m.group(1)) else m.group(0), text)


def _write(out: Path, name: str, lines: list[str], product: bool = False) -> None:
    tool = "tools/gen_docs.py" if product else "tools/gen_engine_docs.py"
    out.mkdir(parents=True, exist_ok=True)
    body = "\n".join(lines).rstrip() + "\n"
    text = (f"<!-- GENERATED by {tool} -- do not edit by hand. -->\n"
            f"<!-- Regenerate with: {'PY' if product else 'python'} {tool} -->\n\n"
            + (without_plan_codes(body) if product else body))
    (out / name).write_text(text, encoding="utf-8", newline="\n")


def _no_ref(text: str, product: bool) -> str:
    """*text* where `][` cannot read as a Markdown reference link. The engine site's
    mkdocstrings plugin resolves `[a][b]` as a cross-reference, and the optional-argument
    notation `f(x[, a][, b])` looks like one; the product site has no such plugin."""
    return text if product else text.replace("][", "]" + chr(92) + "[")


