#
# One page per block type and per distribution, one per group of expression functions, and an
# index for each. What a page shows is run here, so a number on it is the engine's: a block's
# example is a snippet (`docs/snippets/blocks/<TYPE>.py`) and its output, a distribution's
# figures are drawn from a seeded stream, a function's value is the expression evaluated.
# "Used in" lists come from the bundled models and from the hand-written pages, so a page
# changes when either does; the generated-pages test says so.

ELEMENT_SEED = 0
DRAWS = 10_000                  # a distribution's mean, variance and chart come from this many draws
BLOCK_SNIPPETS = DOCS / "snippets" / "blocks"
BLOCK_SNIPPET_OF = {"SUB_ENTRY": "SUBMODEL", "SUB_EXIT": "SUBMODEL"}    # one example shows all three
EDITOR_ONLY = ("SUBMODEL", "SUB_ENTRY", "SUB_EXIT")
# A result frame every run has, or a log: the page of a block lists the others its example fills.
COMMON_FRAMES = ("system", "entity_summary", "entity_log", "timeseries", "dashboard")
# Pages that are not hand-written guidance, and files that only repeat what others say.
GUIDE_SKIP = ("reference", "gallery", "validation", "worked-examples", "schema", "snippets", "elements", "img")
GUIDE_SKIP_FILES = ("changelog.md", "whats-new.md", "contributing.md")
SHOWN = 6                       # most guides or models a "used in" line names before "and N more"


def _page_name(name: str) -> str:
    """The file a block or distribution has: `BoundedNormal` is `bounded-normal`, `SUB_ENTRY` `sub-entry`."""
    return re.sub(r"(?<=[a-z0-9])(?=[A-Z])", "-", name).replace("_", "-").lower()


def _paragraphs(text: str) -> list[str]:
    return [" ".join(p.split()) for p in inspect.cleandoc(text or "").split("\n\n") if p.strip()]


def _fragment(kind: str, name: str, heading: str) -> list[str]:
    """The hand-written part of a page, `docs/elements/<kind>/<name>.md`: nothing when there is none."""
    path = DOCS / "elements" / kind / f"{name}.md"
    if not path.is_file():
        return []
    return [f"## {heading}", "", path.read_text(encoding="utf-8").strip(), ""]


