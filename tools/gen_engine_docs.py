def _function_signature(name: str) -> tuple[str, str]:
    """(call, description) of a function, from its note."""
    note = FUNCTION_NOTES.get(name, "")
    found = re.match(rf"({re.escape(name)}\(.*?\)): (.*)$", note, re.S)
    if found:
        return found.group(1), found.group(2)
    _fn, _ctx, low, high = FUNCTIONS[name]
    if name in FUNCTION_SIGNATURES:
        return FUNCTION_SIGNATURES[name], note
    placeholders = ["x", "y", "z", "w"]
    shown = ", ".join(placeholders[:low]) + (", ..." if high is None else "")
    return f"{name}({shown})" if high in (low, None) else f"{name}({', '.join(placeholders[:low])}[, {placeholders[low]}])", note


def _scope_values(names: list[str]) -> dict:
    import numpy as np
    from nagasim.core.expressions import ExpressionScope, compile_expression

    rng = np.random.default_rng(ELEMENT_SEED)
    return {name: compile_expression(FUNCTION_EXAMPLES[name]).evaluate(ExpressionScope(rng=rng)) for name in names}


def _model_values(names: list[str]) -> dict:
    """Each expression as an auxiliary of one small model, read at its last time."""
    import logging
    from nagasim import build as nb

    m = nb.Model(time_limit=20, time_unit="hours", sd={"dt": 0.5, "method": "rk4"},
                 network={"nodes": [{"name": "dock", "x": 0, "y": 0}, {"name": "yard", "x": 100, "y": 0}],
                          "segments": [{"from": "dock", "to": "yard", "length": 100, "two_way": True}]})
    m.add_auxiliary(name="base", expr="4")
    m.add_variable(name="batch_size", initial=12)
    m.add_level(name="Tank", capacity=100, initial=40)
    m.add_flow(name="fill", rate="2", to="Tank", tag="water", rate_time_unit="hours")
    m.add_delay(name="pipe", input="STEP(10, 5)", delay_time="4", kind="material")
    m.add_timeseries_input(name="demand", times=[0, 5], values=[10, 20])
    m.add_table(name="curve", keys=[0, 5, 10], values=[0, 50, 60], key_mode="linear")
    m.add_resource(name="Desk", capacity=2)
    m.add_resource(name="Pump", capacity=1, power={"busy": 7, "idle": 1})
    m.add_subscript(name="region", elements=["north", "south", "east"])
    m.add_auxiliary(name="sales", dims=["region"], expr="10", elements={"south": "20", "east": "30"})
    m.add_level(name="Silo", capacity=500, initial=300)
    m.add_flow(name="feed", rate="5", rate_time_unit="hours", **{"from": "Silo"})
    m.add_conversion(name="Digester", cohort_interval=1, unit="Nm3", substrates=[
        {"name": "maize", "feed": 'FLOW("feed")', "yield": 10.0, "half_life": 5, "steps": 6,
         "components": {"ch4": 0.6}, "feed_time_unit": "hours"}])
    m.add_level(name="Holder", capacity=1000, initial=100, unit="Nm3",
                components=[{"name": "ch4", "initial_fraction": 0.5}])
    m.add_flow(name="gas", to="Holder", rate='CONV("Digester")', rate_time_unit="hours",
               components={"ch4": 'FRACTION("Digester", "ch4")'})
    m.create(distribution=nb.Exponential(rate=3)) >> m.process(
        resource_name="Desk", distribution=nb.Constant(value=1)) >> m.dispose()
    m.create("parked", distribution=nb.Constant(value=2)) >> m.hold(signal_name="never") >> m.dispose()
    for name in names:
        m.add_auxiliary(name=f"f_{name}", expr=FUNCTION_EXAMPLES[name])
    logging.disable(logging.WARNING)
    try:
        series = m.run(seed=ELEMENT_SEED)["timeseries"]
    finally:
        logging.disable(logging.NOTSET)
    last = series[series["Time"] == series["Time"].max()].set_index("Series")["Value"]
    return {name: float(last[f"aux/f_{name}"]) for name in names}


def _agent_values(names: list[str]) -> dict:
    """Each expression read by agent 0 of a small population, from the log of an attribute it sets."""
    import logging
    from nagasim import build as nb

    m = nb.Model(time_limit=2)
    todo = [n for n in names if n not in NOT_EVALUATED]
    m.add_agent_type(
        name="Walker", states=[{"name": "Red"}, {"name": "Blue"}], initial_state="Red",
        attributes=[{"name": "w", "init": "self.id + 1"}] + [{"name": f"p_{n}", "init": "0"} for n in todo],
        space={"kind": "grid", "size": [4, 4], "cell": 1, "torus": False, "neighbourhood": "moore",
               "patches": [{"name": "food", "init": "cx + cy"}]},
        tick={"dt": 1}, on_tick=[{"target": f"self.p_{n}", "expr": FUNCTION_EXAMPLES[n]} for n in todo])
    m.add_population(name="Pop", type="Walker", count=4, network={"kind": "small_world", "k": 2, "beta": 0},
                     placement={"kind": "table", "points": [[0, 0], [1, 0], [1, 1], [3, 3]]})
    logging.disable(logging.WARNING)
    try:
        log = m.run(seed=ELEMENT_SEED)["agent_attribute_log"]
    finally:
        logging.disable(logging.NOTSET)
    return {n: float(log[log["Attribute"] == f"p_{n}"]["Value"].iloc[0]) for n in todo}


@functools.lru_cache(maxsize=None)
def function_values() -> dict:
    """{function: value of its example}, every example run once."""
    evaluate = {"scope": _scope_values, "model": _model_values, "agents": _agent_values}
    values: dict = {}
    for how, run in evaluate.items():
        values.update(run([n for _p, _t, _s, group_how, names in FUNCTION_GROUPS if group_how == how for n in names]))
    return values


def _function_page(group: tuple, product: bool) -> list[str]:
    page, title, summary, how, names = group
    values = function_values()
    lines = [f"# {title}", "", summary, "", EVALUATION_NOTES[how], ""]
    lines += _fragment("functions", page, "Typical uses")
    for name in sorted(names, key=str.lower):
        call, description = _function_signature(name)
        _fn, _ctx, low, high = FUNCTIONS[name]
        arity = "no arguments" if high == 0 else f"{low} argument{'s' * (low != 1)}" if high == low else \
            f"{low} or more arguments" if high is None else f"{low} to {high} arguments"
        description = _no_ref(description, product).rstrip(".") or "(no description yet)"
        lines += [f"## {name}", "", f"`{_no_ref(call, product)}`: {arity}.", "", f"{description}.", ""]
        if name in values:
            lines += [f"Example: `{FUNCTION_EXAMPLES[name]}` gives {_sig(values[name], 4)}.", ""]
        else:
            lines += [f"Example: `{FUNCTION_EXAMPLES[name]}`. No value is shown: {NOT_EVALUATED[name]}.", ""]
        models = [title_ for _stem, title_, _category, _layout, text in _models()
                  if re.search(rf"\b{name}\(", text)]
        if models:
            lines += [f"Used in the bundled models {_more(models, 4)}.", ""]
    guides = _guides_naming(re.compile(rf"\b(?:{'|'.join(map(re.escape, names))})\("), product)
    lines += ["## See also", "", "- [All function groups and the grammar](index.md), "
              "[Distributions](../distributions/index.md)"]
    if guides:
        lines.append(f"- Guides that use them: {_more(guides)}")
    return lines


def gen_expressions(out: Path, product: bool = False) -> None:
    placed = [name for *_head, names in FUNCTION_GROUPS for name in names]
    assert sorted(placed) == sorted(FUNCTIONS) and sorted(FUNCTION_EXAMPLES) == sorted(FUNCTIONS), (
        f"FUNCTION_GROUPS and FUNCTION_EXAMPLES must place every function once; missing "
        f"{sorted(set(FUNCTIONS) - set(placed))}, unknown {sorted(set(placed) - set(FUNCTIONS))}")
    lines = ["# Expression reference", "",
             "`core/expressions.py`'s grammar: a restricted-Python AST allow-list, never `eval`/`exec`"
             + (" (see [Expressions and variables](../../modelling-guide/expressions-variables.md))."
                if product else "."), "",
             "## Grammar", "",
             "| Category | Allowed |", "|---|---|",
             "| Constants | int, float, str, bool, None |",
             "| Names | `entity`, `TNOW` / `now`, `true` / `false`, submodel parameters, model variables |",
             "| Attributes | `entity.<name>`; `self.<name>` in an agent type's expressions (its "
             "attributes, `self.state`, `self.id`); `AGENT(\"pop\", i).<name>`; no leading "
             "`_`. `payload` in a message transition's guard and actions |",
             "| Operators | `+ - * / // % **`, unary `+ - not`, `and`/`or`, comparisons, "
             "`in`/`not in` against a tuple or list literal, `a if c else b`, tuple and list literals |",
             "| Calls | the functions below, positional arguments only |", "",
             *_fragment("functions", "index", "Names and case"),
             "## Functions", "",
             "One page for each group; every function has its call, what it does and an example with the "
             "value it gives.", "", "| Group | Functions |", "|---|---|"]
    for group in FUNCTION_GROUPS:
        page, title, _summary, _how, names = group
        lines.append(f"| [{title}]({page}.md) | {', '.join(f'`{n}`' for n in sorted(names, key=str.lower))} |")
        _write(out / "functions", f"{page}.md", _function_page(group, product), product)
    _write(out / "functions", "index.md", lines, product)


