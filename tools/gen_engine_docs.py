def _sig(value: float, digits: int = 3) -> str:
    """*value* at *digits* significant digits. That is what a page prints: the last digits
    of a float differ between systems and library versions, the first three do not."""
    if value != value:
        return "--"
    rounded = float(f"{value:.{digits}g}")
    return f"{int(rounded):,}" if rounded == int(rounded) else f"{rounded:.{digits}g}"


