# A map of the site for an LLM agent (llmstxt.org): every page of the nav, with its title,
# its first sentence and the address of the built page.

def site_nav() -> tuple[dict, list[tuple[str, str | None, str]]]:
    """mkdocs.yml, and (section, title, path) for every page of its nav, in order."""
    import yaml

    class Loader(yaml.SafeLoader):
        """A safe loader that reads the config's one `!!python/name` tag (an extension's
        formatter) as nothing: no object is ever built from the file."""

    Loader.add_multi_constructor("tag:yaml.org,2002:python/", lambda loader, suffix, node: None)
    config = yaml.load((SITE / "mkdocs.yml").read_text(encoding="utf-8"), Loader=Loader)

    def walk(items, section):
        for item in items:
            if isinstance(item, str):
                yield section, None, item
                continue
            (title, value), = item.items()
            if isinstance(value, str):
                yield section, title, value
            else:
                yield from walk(value, title)

    return config, list(walk(config["nav"], ""))


def _summary(text: str) -> tuple[str, str]:
    """(the page's heading, its first sentence); neither for a page that only includes a
    file of the repository (the changelog), whose first lines change with every release."""
    import re

    if text.startswith("--8<--"):
        return "", ""
    lines = [line.strip() for line in text.split("\n")]
    heading = next(line[2:] for line in lines if line.startswith("# "))
    after = lines[lines.index("# " + heading) + 1:]
    start = next(i for i, line in enumerate(after)
                 if line and not line.startswith(("<!--", "#", "|", "```", "![")))
    paragraph = " ".join(after[start:after.index("", start) if "" in after[start:] else None])
    paragraph = re.sub(r"\[([^\]]+)\]\([^)]+\)", r"\1", paragraph).replace("**", "").replace("`", "")
    return heading, paragraph.split(". ", 1)[0].rstrip(".:") + "."


def llms_txt() -> str:
    config, nav = site_nav()
    base = config["site_url"].rstrip("/") + "/"
    lines = [f"# {config['site_name']}", "", f"> {config['site_description']}. A model is a JSON "
             "file of blocks, resources, stocks and flows, and agents; the engine runs it and "
             "returns statistics as pandas frames. Command `naga`, Python package `nagasim`.", "",
             "Every page of the documentation, in the order of its menu. An agent that builds "
             "models should start with the model file format, the block reference and the agent "
             "tools."]
    section = None
    for group, title, path in nav:
        if group != section:
            section = group
            lines += ["", f"## {group or 'Start'}", ""]
        heading, sentence = _summary((DOCS / path).read_text(encoding="utf-8"))
        lines.append(f"- [{title or heading}]({base}{path[:-3]}.html)"
                     + (f": {sentence}" if sentence else ""))
    return "\n".join(lines) + "\n"


def gen_llms(out: Path) -> None:
    out.mkdir(parents=True, exist_ok=True)
    (out / "llms.txt").write_text(llms_txt(), encoding="utf-8", newline="\n")


