def section_example(name: str) -> tuple:
    """(fragment, the other sections it refers to) of a section."""
    example = SECTION_EXAMPLES[name]
    return example if isinstance(example, tuple) else (example, {})


def _resolve(schema: dict, node: dict) -> dict:
    return schema["$defs"][node["$ref"].split("/")[-1]] if "$ref" in node else node


def _kind(schema: dict, node: dict) -> str:
    """How a field's value reads: its JSON type, a choice, a list of something, or a named shape."""
    if "$ref" in node:
        return schema["$defs"][node["$ref"].split("/")[-1]].get("title") or node["$ref"].split("/")[-1].replace("_", " ")
    if "enum" in node:
        return "choice"
    if "const" in node:
        return f"`{node['const']}`"
    for branch in ("anyOf", "oneOf"):
        if branch in node:
            kinds = list(dict.fromkeys(_kind(schema, b) for b in node[branch]))
            return " or ".join(kinds)
    kind = node.get("type", "any")
    if isinstance(kind, list):
        return " or ".join(kind)
    if kind == "array":
        return "list of " + _kind(schema, node["items"]) if node.get("items") else "list"
    return kind


def _section_shape(schema: dict, section) -> tuple[str, dict, list[str]]:
    """(how the section's value reads, the object whose keys are its fields, those keys that are required)."""
    node = _resolve(schema, schema["properties"][section.name])
    shape = "an object"
    if node.get("type") == "array":
        item = _resolve(schema, node["items"])
        if section.name == "blocks":
            variants = item["oneOf"]
            common = {k: variants[0]["properties"][k] for k in variants[0]["properties"]
                      if all(k in v["properties"] for v in variants)}
            common["type"] = {"type": "string", "enum": sorted(v["title"] for v in variants),
                              "description": "The block type; it decides which parameters the block takes."}
            common["params"] = {"type": "object", "description": "The block type's parameters, by name "
                                "(see the [block reference](../blocks/index.md))."}
            return ("a list of blocks. The `type` picks the block type and `params` holds that type's "
                    "parameters (see the [block reference](../blocks/index.md))",
                    {"properties": common, "required": ["name", "type"]}, ["name", "type"])
        shape = f"a list of `{section.item}` entries" if section.item else "a list of entries"
        if section.key:
            shape += f", each named by its `{section.key}`"
        node = item
    elif "anyOf" in node:
        node = _resolve(schema, node["anyOf"][-1])
        shape = "`null`, or an object"
    elif isinstance(node.get("additionalProperties"), dict) and not node.get("properties"):
        node = _resolve(schema, node["additionalProperties"])
        shape = "an object that maps a definition's name to its definition"
    return shape, node, list(node.get("required") or [])


def _text(value: str, product: bool) -> str:
    """A description as one table cell: a `<name>` outside backticks would read as an HTML tag."""
    cell = " ".join(without_plan_codes(value or "").split()).replace("|", chr(92) + "|")
    parts = cell.split("`")
    parts[::2] = [p.replace("<", "&lt;").replace(">", "&gt;") for p in parts[::2]]
    return _no_ref("`".join(parts), product)


def _field_row(schema: dict, name: str, node: dict, required: list[str], product: bool) -> str:
    target = _resolve(schema, node)
    description = node.get("description") or target.get("description") or ""
    description = description.split("\n\n")[0]
    if "enum" in node:
        description += " One of " + ", ".join(f"`{v}`" for v in node["enum"]) + "."
    elif "enum" in target and target is not node:
        description += " One of " + ", ".join(f"`{v}`" for v in target["enum"]) + "."
    unit = node.get("x-unit-key")
    quantity = node.get("x-quantity")
    unit_cell = (f"{quantity} (`{unit}`)" if unit and quantity else f"`{unit}`" if unit else quantity or "")
    default = f"`{json.dumps(node['default'])}`" if "default" in node else ""
    return (f"| `{name}` | {_text(_kind(schema, node), product)} | {'yes' if name in required else ''} | "
            f"{default} | {unit_cell} | {_text(description, product) or '--'} |")


def builder_code(section, fragment) -> str | None:
    """The Python that writes the fragment, as the builder offers it: it leaves the model in `m`.
    None for a section the builder writes by another call (links, submodels)."""
    from nagasim import build as nb

    if section.name == "blocks":
        return "\n".join(["from nagasim import build as nb", "m = nb.Model()",
                          "arrive = m.create(distribution=nb.Exponential(rate=1.0))", "leave = m.dispose()",
                          "arrive >> leave        # links the two blocks"])
    method = next((m for m, s in nb._RECORDS.items() if s.name == section.name), None)
    if method:
        entry = fragment[0]
        call = (f"m.{method}(" + (", ".join(f"{k}={v!r}" for k, v in entry.items())
                                  if all(k.isidentifier() and not keyword.iskeyword(k) for k in entry)
                                  else f"**{entry!r}") + ")")
        return "\n".join(["from nagasim import build as nb", "m = nb.Model()", call])
    if section.name in ("links", "submodels"):
        return None
    return f"from nagasim import build as nb\nm = nb.Model({section.name}={fragment!r})"


def _builder_lines(section, fragment) -> list[str]:
    code = builder_code(section, fragment)
    if section.name == "links":
        return ["In the Python builder `a >> b` adds a link, and `m.link(a, b, delay=...)` adds one with keys.", ""]
    if section.name == "submodels":
        return ["In the Python builder `m.definition(name)` adds a definition and returns the canvas to build it on.", ""]
    lead = ("In the Python builder each block type is a method named after it:" if section.name == "blocks"
            else "In the Python builder:" if code.count("\n") == 2 and ".add_" in code
            else "In the Python builder the section is a keyword of `Model`:")
    return [lead, "", "```python", code, "```", ""]


def _section_page(section, schema: dict, product: bool) -> list[str]:
    shape, node, required = _section_shape(schema, section)
    fragment, needs = section_example(section.name)
    lines = [f"# {section.name}", "", _no_ref(without_plan_codes(" ".join(section.doc.split())), product), ""]
    described = " ".join((_resolve(schema, schema["properties"][section.name]).get("description") or "").split())
    if described and described != " ".join(section.doc.split()):
        lines += [_no_ref(without_plan_codes(described), product), ""]
    lines += [f"In the model file this key holds {shape}.", ""]
    flags = []
    if section.overridable:
        path = ("links.<source>-><target>.<field>" if section.name == "links"
                else "blocks.<name>.params.<parameter>" if section.name == "blocks"
                else f"{section.name}.<{section.key}>.<field>" if section.key else f"{section.name}.<field>")
        flags.append(f"A scenario, an experiment or an optimizer can set a field by the path `{path}`.")
    if section.bindable:
        flags.append("A data binding can write a field.")
    lines += [" ".join(flags), ""] if flags else []
    lines += _fragment("sections", section_family(section.name), "Typical uses")
    lines += ["## Fields", "", "| Field | Type | Required | Default | Unit | Description |", "|---|---|---|---|---|---|"]
    properties = node.get("properties") or {}
    lines += [_field_row(schema, name, prop, required, product) for name, prop in properties.items()]
    lines += ["", "A field of a nested object is described in the JSON Schema (`naga schema`).", ""]
    lines += ["## Example", ""]
    if needs:
        lines += ["The fragment refers to entries that are defined elsewhere in the same file:", "",
                  "```json", json.dumps(needs), "```", "", "The fragment:", ""]
    lines += ["```json", json.dumps({section.name: fragment}), "```", ""]
    lines += _builder_lines(section, fragment)
    models = [_model_link(stem, title, category, product) for stem, title, category, layout, _text_ in _models()
              if layout.get(section.name)]
    lines += _used_in(models, _guides_naming(re.compile(rf"`{section.name}`|\"{section.name}\""), product))
    lines += ["## See also", "",
              "- [All sections](index.md), [Model file keys](../schema.md), [Model file format](../../model-file-format.md)"]
    return lines


def gen_sections(out: Path, product: bool = False) -> None:
    from nagasim import modelschema

    schema = modelschema.build_json_schema()
    index = ["# Model file sections", "",
             "One page per top-level key of the model file, from the published JSON Schema "
             "(`naga schema`): what the key holds, each field with its type, default and unit, and an "
             "example fragment that the schema and the checks accept. "
             "[Model file keys](../schema.md) lists the keys with the version history.", "",
             "| Section | Holds | What it is for |", "|---|---|---|"]
    for section in sections.SECTIONS:
        shape = _section_shape(schema, section)[0].split(". ")[0].split(",")[0]
        index.append(f"| [`{section.name}`]({section.name}.md) | {shape} | "
                     f"{_first_sentence(section.doc).replace('|', chr(92) + '|')} |")
        _write(out / "model-file", f"{section.name}.md", _section_page(section, schema, product), product)
    _write(out / "model-file", "index.md", index, product)


