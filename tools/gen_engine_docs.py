def gen_kpis(out: Path, product: bool = False) -> None:
    from nagasim.api import run_model

    model_path = ROOT / "nagasim" / "models" / "job_shop_jackson.json"
    results = run_model(str(model_path), replications=1, seed=0, warmup=0, run_length=300)

    missing: list[str] = []
    frame_columns: dict[str, list[str]] = {}
    for frame_name, df in results.items():
        cols = list(df.columns)
        frame_columns[frame_name] = cols
        # "system" and "user_summary" carry the real KPI names as row values
        # (a "Metric"/"Statistic" + "Value" long format), not as columns --
        # document those names instead of the two generic column labels.
        names_to_check = cols
        if frame_name == "system" and "Metric" in cols:
            names_to_check = [c for c in cols if c != "Metric"] + list(df["Metric"])
        for col in names_to_check:
            if col not in KPI_DEFINITIONS:
                missing.append(f"{frame_name}.{col}")
    if missing:
        raise SystemExit(
            "kpis.md generation found columns with no definition in "
            f"KPI_DEFINITIONS: {missing}. Add a definition for each in tools/gen_engine_docs.py."
        )

    lines = ["# KPI reference", "",
             "Every result frame `nagasim.api.run_model` / `nagasim.experiments.run_scenarios` return, "
             "and every column each one carries -- probed against `nagasim/models/job_shop_jackson.json` "
             "so a new KPI column fails this generation until it has a definition here.", ""]
    for frame_name in ("system", "entity_summary", "entity_log", "resource_summary", "resource_log",
                       "store_summary", "store_log", "user_summary", "order_summary",
                       "due_date_summary", "queue_summary", "motion_summary",
                       "charging_summary", "battery_summary", "tending_summary", "timeseries"):
        cols = frame_columns.get(frame_name, [])
        lines += [f"## {frame_name}", ""]
        if frame_name == "system":
            lines.append("One row per metric (`Metric`, `Value` columns). Metrics observed on the probe run:")
            lines += ["", "| Metric | Definition |", "|---|---|"]
            for metric in results[frame_name]["Metric"]:
                lines.append(f"| `{metric}` | {KPI_DEFINITIONS[metric]} |")
