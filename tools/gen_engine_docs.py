def _capture_help(args, main) -> str:
    """One command's `--help`, rendered IN PROCESS by *main* (`nagasim.cli.main`).

    Every sub-parser sets its own `prog`, so this is byte-identical to the real
    command's output -- for one thing argparse needs pinned: COLUMNS, which it
    wraps on, so the page does not depend on the terminal this is run from.
    """
    previous = os.environ.get("COLUMNS")
    os.environ["COLUMNS"] = "80"
    out = io.StringIO()
    try:
        with contextlib.redirect_stdout(out), contextlib.redirect_stderr(out):
            main(list(args))
    except SystemExit:
        pass            # --help always exits
    finally:
        if previous is None:
            os.environ.pop("COLUMNS", None)
        else:
            os.environ["COLUMNS"] = previous
    return out.getvalue().strip()


def gen_cli(out: Path) -> None:
    from nagasim.cli import COMMANDS, main

    lines = ["# Command line reference", "",
             "`--help` output of every `naga` command, captured live so it cannot drift from "
             "the real argument parsers. `python -m nagasim` is the same program.", "",
             "| Command | What it does |", "|---|---|"]
    lines += [f"| [`naga {name}`](#naga-{name}) | {summary} |"
              for name, (_module, _attr, summary) in COMMANDS.items()]
    for name in COMMANDS:
        lines += ["", f"## naga {name}", "", "```text", _capture_help([name, "--help"], main), "```"]
    _write(out, "cli.md", lines)


