def engine_tools() -> list:
    """The engine's own agent tools, in registration order. A product that is imported in
    the same process adds its tools to the same registry; `origin` tells them apart."""
    from nagasim import agent_tools

    return [spec for spec in agent_tools.TOOLS.values() if spec.origin.startswith("nagasim.")]


def _first_sentence(text: str) -> str:
    paragraph = " ".join((text or "").strip().split("\n\n", 1)[0].split())
    return paragraph.split(". ", 1)[0].rstrip(".") + "." if paragraph else ""


def product_tools() -> list:
    """The agent tools the product registers on top of the engine's, in registration order."""
    from nagasim import agent_tools
    import product.agent_tools  # noqa: F401  registers the product's tools

    return [spec for spec in agent_tools.TOOLS.values() if not spec.origin.startswith("nagasim.")]


def gen_tools(out: Path, product: bool = False) -> None:
    """The engine's tools; with *product*, the product's own (the page the product site shows)."""
    tools = product_tools() if product else engine_tools()
    if product:
        lines = ["# Agent tools", "",
                 f"The {len(tools)} tools the Naga editor adds to the engine's. They are published "
                 "under the same names by `naga mcp` and by the editor's assistant. \"Reads\" marks a "
                 "tool that changes nothing. Each tool's full description and argument schema is what the "
                 "server sends an agent; see [Use with an agent](../use-with-claude.md)."]
    else:
        lines = ["# Agent tools", "",
                 f"The {len(tools)} tools of `nagasim.agent_tools.TOOLS`, which `naga mcp` publishes "
                 "under the same names. \"Reads\" marks a tool that changes nothing. Each tool's full "
                 "description and argument schema is what the server sends an agent; "
                 "see [Use with an agent](../mcp.md)."]
    group = None
    for spec in tools:
        if spec.origin != group:
            group = spec.origin
            lines += ["", f"## {group.rsplit('.', 1)[-1]}", "",
                      "| Tool | Reads | What it does |", "|---|---|---|"]
        summary = _first_sentence(spec.description).replace("|", "\\|")
        lines.append(f"| `{spec.name}` | {'yes' if spec.read_only else ''} | {summary} |")
    _write(out, "tools.md", lines, product)


