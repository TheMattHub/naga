@functools.lru_cache(maxsize=None)
def _block_probe(type_name: str) -> tuple[str, str, tuple]:
    """(code, output, [(frame, columns)]) of a block's example: the snippet, what it prints, and
    the result frames it filled beyond the ones every run has."""
    source = BLOCK_SNIPPETS / f"{BLOCK_SNIPPET_OF.get(type_name, type_name)}.py"
    output, namespace = _exec_snippet(source)
    frames = tuple((name, tuple(map(str, frame.columns))) for name, frame in namespace["results"].items()
                   if name not in COMMON_FRAMES and not name.endswith("_log") and len(frame.columns) and len(frame))
    return source.read_text(encoding="utf-8").rstrip("\n"), output.rstrip("\n"), frames


def _ports(spec) -> list[str]:
    names = {p.name for p in spec.params}
    inputs = "none: a flow starts here." if spec.family == "source" else "any number of incoming links."
    if spec.family == "sink":
        outputs = "none: a flow ends here."
    elif spec.multi_output:
        outputs = "several, one for each branch; the block picks the link by its index at run time."
    else:
        outputs = "one outgoing link."
        if {"balk_if", "renege_after"} <= names:
            outputs += (" With `balk_if` or `renege_after` set, a second link (index 1) takes the "
                        "entities that leave without service.")
    return ["## Ports", "", f"- Inputs: {inputs}", f"- Outputs: {outputs}", ""]


def _block_page(type_name: str, product: bool) -> list[str]:
    spec = BLOCK_REGISTRY[type_name]
    paragraphs = _paragraphs(spec.cls.__doc__) or ["(no description yet)"]
    lines = [f"# {type_name}", "", *sum(([p, ""] for p in paragraphs), [])]
    lines += [f"Family: {spec.family or 'other'}. Python builder: `m.{type_name.lower()}(...)`."
              + (" Editor-only: the engine flattens it away before a run." if type_name in EDITOR_ONLY else ""), ""]
    lines += _fragment("blocks", type_name, "Typical uses")
    lines += _ports(spec)
    lines += ["## Parameters", ""]
    if spec.params:
        lines += ["| Parameter | Type | Default | Required | Quantity | Unit key | Description |",
                  "|---|---|---|---|---|---|---|"]
        for p in spec.params:
            quantity = "" if p.quantity in (None, "none") else p.quantity
            unit = f"`{p.unit_field}`" if p.unit_field else ""
            lines.append(f"| `{p.name}` | {p.type.__name__} | `{p.default!r}` | "
                         f"{'yes' if p.required else ''} | {quantity} | {unit} | "
                         f"{_no_ref(p.description, product) or '--'} |")
    else:
        lines.append("No parameters.")
    code, output, frames = _block_probe(type_name)
    lines += ["", "## Statistics", "",
              "Every run fills `system` and `entity_summary` (see the [KPI reference](../kpis.md)). "
              "The example below also fills:", ""]
    if frames:
        lines += ["| Frame | Columns |", "|---|---|"]
        for frame, columns in frames:
            name = f"[`{frame}`](../kpis.md#{frame})" if frame in KPI_FRAMES else f"`{frame}`"
            lines.append(f"| {name} | {', '.join(f'`{c}`' for c in columns)} |")
    else:
        lines.append("No further frame.")
    codes = [code_ for code_, text in schema_mod.PROBLEM_CODES.items() if re.search(rf"\b{type_name}\b", text)]
    lines += ["", "## Problem codes", ""]
    if codes:
        lines += ["A check of the model reports these about this block:", "",
                  "| Code | Meaning |", "|---|---|"]
        lines += [f"| `{c}` | {without_plan_codes(schema_mod.PROBLEM_CODES[c]).replace('|', chr(92) + '|')} |"
                  for c in sorted(codes)]
    else:
        lines.append("No check names this block type.")
    lines += ["", "## Example", "",
              "The snippet seeds itself; its output is from a run made when this page was generated."
              + (" `SUB_ENTRY` and `SUB_EXIT` are the ports of a definition, `SUBMODEL` an instance of it."
                 if type_name in EDITOR_ONLY else ""),
              "", "```python", code, "```", "", "```text", output, "```", ""]
    models = [_model_link(stem, title, category, product) for stem, title, category, layout, _text in _models()
              if any(b.get("type") == type_name for b in _blocks_of(layout))]
    pattern = re.compile(rf"\b{type_name}\b|\bm\.{type_name.lower()}\(")
    lines += _used_in(models, _guides_naming(pattern, product))
    siblings = [f"[{t}]({_page_name(t)}.md)" for t in sorted(BLOCK_REGISTRY)
                if t != type_name and BLOCK_REGISTRY[t].family == spec.family]
    lines += ["## See also", "",
              f"- [All blocks](index.md), [KPI reference](../kpis.md), [Model file keys](../schema.md), "
              "[Model file format](../../model-file-format.md)"]
    if siblings:
        lines.append(f"- Same family ({spec.family}): {_more(siblings, 8)}")
    return lines


def gen_blocks(out: Path, product: bool = False) -> None:
    index = ["# Block reference", "",
             "One page per block type, from `nagasim/core/block_registry.py`: what it does, its ports and "
             "parameters, the result frames it fills, the checks that name it, and an example that runs "
             "when the page is generated. Types marked *editor-only* never run: the engine flattens them "
             "away before a run"
             + (" (see [Submodels](../../modelling-guide/submodels.md))." if product else "."),
             "", "| Block | Family | What it does |", "|---|---|---|"]
    for type_name in sorted(BLOCK_REGISTRY):
        spec = BLOCK_REGISTRY[type_name]
        summary = _first_sentence(spec.cls.__doc__) or "(no description yet)"
        index.append(f"| [{type_name}]({_page_name(type_name)}.md) | {spec.family or 'other'} | "
                     f"{summary.replace('|', chr(92) + '|')}{' (editor-only)' if type_name in EDITOR_ONLY else ''} |")
        _write(out / "blocks", f"{_page_name(type_name)}.md", _block_page(type_name, product), product)
    _write(out / "blocks", "index.md", index, product)


