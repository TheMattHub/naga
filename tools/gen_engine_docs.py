@functools.lru_cache(maxsize=None)
def _draws(name: str) -> tuple:
    """(analytic mean or None, [draws]) of *name* with its example parameters, from the seeded stream."""
    import numpy as np
    from nagasim.core.distributions import StochasticDistribution, distribution_mean

    params = DISTRIBUTION_EXAMPLES[name]
    rng = np.random.default_rng(ELEMENT_SEED)
    dist = StochasticDistribution(name, params)
    count = len(params["schedule"]) if name == "FixedSchedule" else DRAWS      # it runs out of times
    return distribution_mean(name, params), tuple(float(dist.sample(rng)) for _ in range(count))


def _chart(name: str, draws: tuple) -> str:
    """The SVG of the draws: a bar for each value of a discrete distribution, else a histogram of
    the central 99 percent (a heavy tail would squeeze the rest into one bar)."""
    import numpy as np
    from nagasim import svgcharts

    x = np.array(draws)
    if np.all(x == np.round(x)) and len(np.unique(x)) <= 40:
        values, counts = np.unique(x, return_counts=True)
        svg = svgcharts.bar_chart(f"{name}: share of {DRAWS:,} draws", [f"{v:g}" for v in values],
                                  [float(c) / len(x) for c in counts], "share")
    else:
        low, high = np.percentile(x, [0.5, 99.5])
        counts, edges = np.histogram(x[(x >= low) & (x <= high)], bins=30)
        svg = svgcharts.histogram(f"{name}: {DRAWS:,} draws", [float(e) for e in edges],
                                  [int(c) for c in counts], "value", "draws")
    return svg.replace(">", '><rect width="100%" height="100%" fill="white"/>', 1)      # legible on a dark theme


def _distribution_page(name: str, product: bool) -> list[str]:
    import numpy as np
    from nagasim import build as nb

    spec = DISTRIBUTION_REGISTRY[name]
    params = DISTRIBUTION_EXAMPLES[name]
    assert set(params) == {p.name for p in spec.params}, f"DISTRIBUTION_EXAMPLES[{name!r}] names other parameters than the registry"
    analytic, draws = _draws(name)
    x = np.array(draws)
    lines = [f"# {name}", "", *sum(([p.replace("\n", "  \n"), ""] for p in spec.use_case.split("\n\n")), [])]
    lines += [f"Category: {spec.category}. Arrival: {'yes' if spec.arrival else 'no'}. "
              f"Delay: {'yes' if spec.delay else 'no'}. "
              f"Support lower bound: {spec.support_lower if spec.support_lower is not None else 'unbounded'}."
              + (f" Can be fit from data as `{spec.fit}` (see Input analysis)." if spec.fit else ""), ""]
    lines += ["## Parameters", ""]
    lines += ["| Parameter | Default | Hint |", "|---|---|---|"]
    lines += [f"| `{p.name}` | `{p.default!r}` | {_no_ref(p.hint, product) or '--'} |" for p in spec.params]
    shown = ", ".join(f"{k}={v!r}" for k, v in params.items())
    lines += ["", "## Draws", "", f"With {shown}, {len(draws):,} draws from a stream seeded {ELEMENT_SEED}:", ""]
    if name == "FixedSchedule":
        lines.append(f"It is not random: it returns the listed times in order, then nothing. "
                     f"The first draws are {', '.join(f'{v:g}' for v in draws[:3])}.")
    elif name == "CustomExpression":
        lines += ["| Mean of the draws | Variance of the draws |", "|---|---|",
                  f"| {_sig(float(x.mean()))} | {_sig(float(x.var(ddof=1)))} |"]
    else:
        finite = analytic is not None
        lines += ["| Mean (formula) | Mean of the draws | Variance of the draws |", "|---|---|---|",
                  f"| {_sig(analytic) if finite else 'none: the mean is not finite'} | "
                  f"{_sig(float(x.mean()))} | {_sig(float(x.var(ddof=1)))} |"]
        if not finite:
            lines += ["", "With no finite mean the average of draws does not settle; another seed gives another value."]
    if name != "FixedSchedule":
        lines += ["", f"![{name}: {DRAWS:,} draws]({_page_name(name)}.svg)"]
    call = repr(getattr(nb, name)(**params))            # the builder's own spelling; it checks the names too
    lines += ["", "## Example", "", "In a model file, on any block or section that takes a duration:", "",
              "```json", json.dumps({"distribution": name, "dist_params": params}), "```", "",
              "In the Python builder:", "", "```python", call, "```", ""]
    if name in EXPRESSION_TWINS:
        lines += [f"An expression has its own call for it: `{EXPRESSION_TWINS[name]}`.", ""]
    models = [_model_link(stem, title, category, product) for stem, title, category, layout, _text in _models()
              if name in set(_values_of(layout, ("distribution", "dist_type")))]
    lines += _used_in(models, _guides_naming(re.compile(rf"\b{name}\b"), product))
    lines += ["## See also", "", "- [All distributions](index.md), [Expression functions](../functions/index.md), "
              "[Model file format](../../model-file-format.md)"]
    return lines


def gen_distributions(out: Path, product: bool = False) -> None:
    index = ["# Distribution reference", "",
             "One page per distribution, from `nagasim/core/distributions.py`'s `DISTRIBUTION_REGISTRY`: "
             "its parameters, the mean and variance of seeded draws, a chart of the draws and an example. "
             "\"Arrival\" and \"Delay\" mark whether the distribution is offered for a CREATE inter-arrival "
             "time or for a delay-bearing block (`get_available_distributions`).", "",
             "| Distribution | Category | Arrival | Delay | When to use it |", "|---|---|---|---|---|"]
    for name in sorted(DISTRIBUTION_REGISTRY):
        spec = DISTRIBUTION_REGISTRY[name]
        use = _first_sentence(spec.use_case.split("\n")[0]).replace("|", chr(92) + "|")
        index.append(f"| [{name}]({_page_name(name)}.md) | {spec.category} | {'yes' if spec.arrival else ''} | "
                     f"{'yes' if spec.delay else ''} | {use} |")
        _write(out / "distributions", f"{_page_name(name)}.md", _distribution_page(name, product), product)
        if name != "FixedSchedule":
            (out / "distributions" / f"{_page_name(name)}.svg").write_text(_chart(name, _draws(name)[1]),
                                                                           encoding="utf-8", newline="\n")
    _write(out / "distributions", "index.md", index, product)


