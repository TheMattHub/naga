    out += _signature("__init__", model_params, "None", model_doc)
    for method, section in nb._RECORDS.items():
        item =schema["properties"][section.name]["items"]["$ref"].rsplit("/", 1)[-1]
        props = defs[item].get("properties", {})
        names = [k for k in props if k.isidentifier() and not keyword.iskeyword(k)]
        units = _units_of(SECTION_FIELDS.get(section.name, ()))
        params = ["*"] + [f"{k}: {_unit_kind(_py_type(props[k], defs), units[k]) if k in units else _py_type(props[k], defs)} = ..."
                          for k in names]
        if len(names) < len(props) or defs[item].get("additionalProperties") is not False:
            params.append("**fields: Any")
        doc = [f"Add one entry to `{section.name}` and return its {section.key}. {section.doc}"]
        doc += [""] + [f"{k}: {' '.join(props[k].get('description', '').split())}".rstrip(": ")
                       for k in props]
        out += [""] + _signature(method, params, "Any", doc)
    out += ["",
            "    def definition(self, name: str, **fields: Any) -> Level: ...",
            "    def to_dict(self) -> dict[str, Any]: ...",
            "    def save(self, path: str | PathLike[str]) -> Path: ...",
            "    def run(self, **options: Any) -> Any: ...", "", "",
            "def export_python(layout: str | PathLike[str] | dict[str, Any]) -> str: ...",
            "def main(argv: list[str] | None = None) -> int: ..."]
    return "\n".join(out) + "\n"


