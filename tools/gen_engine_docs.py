def _sig(value: float, digits: int = 3) -> str:
    """*value* at *digits* significant digits. That is what a page prints: the last digits
    of a float differ between systems and library versions, the first three do not."""
    if value != value:
        return "--"
    rounded = float(f"{value:.{digits}g}")
    return f"{int(rounded):,}" if rounded == int(rounded) else f"{rounded:.{digits}g}"


def bundled_models() -> dict[str, list[tuple[Path, dict]]]:
    """{category: [(path, layout)]}, categories and models in name order."""
    import json

    found: dict[str, list] = {}
    for path in sorted(MODELS.glob("*.json")):
        layout = json.loads(path.read_text(encoding="utf-8"))
        category = str((layout.get("info") or {}).get("category") or "Other")
        found.setdefault(category, []).append((path, layout))
    return dict(sorted(found.items()))


def _slug(category: str) -> str:
    return category.lower().replace(" ", "-")


def _headlines(kpis) -> list[tuple[str, float, float]]:
    """(KPI key, mean, 95% half-width) of the few numbers that say what a run gave: the
    system's when entities flowed, the model's own RECORD statistics, its levels' averages
    and its agents' state counts."""
    rows = {metric: (mean, half) for metric, mean, half in zip(kpis["metric"], kpis["mean"], kpis["ci95"])}
    picked: list[str] = []
    if rows.get("system/Total Entities Completed", (0.0,))[0] > 0:
        picked += ["system/Total Entities Completed", "system/Avg Throughput Time"]
        if any(m.startswith("resource/") for m in rows):
            picked += ["system/Avg Queue Length", "system/Avg Resource Usage %"]
    picked += [m for m in rows if m.startswith("user/")][:3]
    picked += [m for m in rows if m.startswith("level/") and m.endswith("/Average")][:3]
    picked += [m for m in rows if m.startswith("agent/") and m.endswith("/Avg Count")][:4]
    if rows.get("system/Total Cost", (0.0,))[0] > 0:
        picked.append("system/Total Cost")
    return [(m, *rows[m]) for m in picked if m in rows and rows[m][0] == rows[m][0]]


def _diagram(layout: dict) -> list[str]:
    """The model's blocks and links as a Mermaid flow chart; nothing for a model with no
    links (stocks and flows, agents) or too many blocks to read."""
    blocks, links = layout.get("blocks") or [], layout.get("links") or []
    if not links or len(blocks) > _DIAGRAM_BLOCKS:
        return []
    ids = {block["name"]: f"b{i}" for i, block in enumerate(blocks)}
    lines = ["```mermaid", "flowchart LR"]
    for block in blocks:
        label = f"{block['name']} ({block['type']})".replace('"', "'")
        lines.append(f'    {ids[block["name"]]}["{label}"]')
    lines += [f"    {ids[link['source']]} --> {ids[link['target']]}" for link in links
              if link.get("source") in ids and link.get("target") in ids]
    return lines + ["```", ""]


def gallery_page(category: str, models: list) -> str:
    import logging

    from nagasim.api import run_model

    lines = [f"# {category}", "",
             f"{len(models)} of the bundled models. The numbers are from a run made when this "
             "page was generated: see [how](index.md#how-the-numbers-are-made)."]
    for path, layout in models:
        info, simulation = layout.get("info") or {}, layout.get("simulation") or {}
        replications = min(GALLERY_REPLICATIONS, int(simulation.get("replications") or 1))
        logging.disable(logging.WARNING)        # a model's own warnings are not the page's
        try:
            kpis = run_model(str(path), replications=replications, seed=GALLERY_SEED).kpis()
        finally:
            logging.disable(logging.NOTSET)
        lines += ["", f"## {info.get('title') or path.stem}", ""]
        if info.get("description"):
            lines += [str(info["description"]).strip(), ""]
        # The command that gives the numbers below: the seed is the command's default.
        asked = int(simulation.get("replications") or 1)
        lines += ["```console", f"naga run {path.stem}"
                  + (f" --replications {replications}" if replications != asked else ""), "```", ""]
        lines += _diagram(layout)
        lines += [f"{replications} replication{'s' if replications > 1 else ''}, seed {GALLERY_SEED}:",
                  "", "| KPI | Mean | 95% half-width |", "|---|---|---|"]
        lines += [f"| `{metric}` | {_sig(mean)} | {_sig(half, 2) if replications > 1 else ''} |"
                  for metric, mean, half in _headlines(kpis)]
    return "\n".join(lines)


