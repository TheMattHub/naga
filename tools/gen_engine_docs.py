def _write(out: Path, name: str, lines: list[str], product: bool = False) -> None:
    tool = "tools/gen_docs.py" if product else "tools/gen_engine_docs.py"
    out.mkdir(parents=True, exist_ok=True)
    text = (f"<!-- GENERATED by {tool} -- do not edit by hand. -->\n"
            f"<!-- Regenerate with: {'PY' if product else 'python'} {tool} -->\n\n"
            + "\n".join(lines).rstrip() + "\n")
    (out / name).write_text(text, encoding="utf-8", newline="\n")


# ---------------------------------------------------------------- blocks.md

def gen_blocks(out: Path, product: bool = False) -> None:
    lines = ["# Block reference", "",
             "One section per block type, from `nagasim/core/block_registry.py`. "
             "Types marked *editor-only* never run: the engine flattens them away before a run"
             + (" (see [Submodels](../modelling-guide/submodels.md))." if product else ".")]
    for type_name in sorted(BLOCK_REGISTRY):
        spec = BLOCK_REGISTRY[type_name]
        doc = " ".join((spec.cls.__doc__ or "").split()) or "(no description yet)"
        lines += ["", f"## {type_name}", "", doc, ""]
        if spec.params:
            lines += ["| Parameter | Type | Default | Required | Quantity | Unit key | Description |",
                      "|---|---|---|---|---|---|---|"]
            for p in spec.params:
                quantity = "" if p.quantity in (None, "none") else p.quantity
                unit = f"`{p.unit_field}`" if p.unit_field else ""
                lines.append(
                    f"| `{p.name}` | {p.type.__name__} | `{p.default!r}` | "
                    f"{'yes' if p.required else ''} | {quantity} | {unit} | "
                    f"{p.description or '--'} |")
        else:
            lines.append("No parameters.")
        outputs = "multiple, chosen at run time" if spec.multi_output else "1"
        lines += ["", f"Outputs: {outputs}."]
    _write(out, "blocks.md", lines, product)


# ---------------------------------------------------------- distributions.md

def gen_distributions(out: Path, product: bool = False) -> None:
    lines = ["# Distribution reference", "",
             "One section per distribution, from `nagasim/core/distributions.py`'s "
             "`DISTRIBUTION_REGISTRY`. \"Arrival\" / \"Delay\" mark whether the distribution is "
             "offered for a CREATE inter-arrival time / a delay-bearing block "
             "(`get_available_distributions`)."]
    for name in sorted(DISTRIBUTION_REGISTRY):
        spec = DISTRIBUTION_REGISTRY[name]
        lines += ["", f"## {name}", "", spec.use_case.replace("\n", "  \n"), "",
                  f"Category: {spec.category}. Arrival: {'yes' if spec.arrival else 'no'}. "
                  f"Delay: {'yes' if spec.delay else 'no'}. "
                  f"Support lower bound: {spec.support_lower if spec.support_lower is not None else 'unbounded'}."
                  + (f" Can be fit from data as `{spec.fit}` (see Input analysis)." if spec.fit else ""),
                  ""]
        if spec.params:
            lines += ["| Parameter | Default | Hint |", "|---|---|---|"]
            for p in spec.params:
                lines.append(f"| `{p.name}` | `{p.default!r}` | {p.hint or '--'} |")
        else:
            lines.append("No parameters.")
    _write(out, "distributions.md", lines, product)


