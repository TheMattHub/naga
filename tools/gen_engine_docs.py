def section_family(name: str) -> str:
    """The family a model-file section belongs to (`SECTION_FAMILIES`)."""
    return next(family for family, names in SECTION_FAMILIES.items() if name in names)


def _more(names: list[str], limit: int = SHOWN) -> str:
    return ", ".join(names[:limit]) + (f" and {len(names) - limit} more" if len(names) > limit else "")


@functools.lru_cache(maxsize=None)
def _guide_pages(product: bool) -> tuple:
    """(path in the site, title, text) of the hand-written pages of the engine's or the product's site."""
    root = ROOT / "site_docs" if product else DOCS
    pages = []
    for path in sorted(root.rglob("*.md")):
        rel = path.relative_to(root).as_posix()
        if rel.split("/")[0] in GUIDE_SKIP or path.name in GUIDE_SKIP_FILES:
            continue
        text = path.read_text(encoding="utf-8")
        title = re.search(r"^# (.+)$", text, re.M)
        pages.append((rel, title.group(1).strip() if title else path.stem, text))
    return tuple(pages)


def _guides_naming(pattern: re.Pattern, product: bool) -> list[str]:
    """Links to the hand-written pages that match *pattern*, the ones that match most often first."""
    hits = [(len(pattern.findall(text)), rel, title) for rel, title, text in _guide_pages(product)
            if pattern.search(text)]
    hits.sort(key=lambda hit: (-hit[0], hit[1]))
    return [f"[{title}](../../{rel})" for _n, rel, title in hits]


@functools.lru_cache(maxsize=None)
def _models() -> tuple:
    """(file stem, title, category, layout, text) of every bundled model."""
    return tuple((path.stem, (layout.get("info") or {}).get("title") or path.stem, category, layout,
                  path.read_text(encoding="utf-8"))
                 for category, models in bundled_models().items() for path, layout in models)


def _model_link(stem: str, title: str, category: str, product: bool) -> str:
    """A bundled model as a link: to its gallery page on the engine's site, to its tutorial on the product's."""
    if not product:
        return f"[{title}](../../gallery/{_slug(category)}.md)"
    tutorial = ROOT / "site_docs" / "tutorials" / f"{stem.replace('_', '-').lower()}.md"
    return f"[{title}](../../tutorials/{tutorial.name})" if tutorial.is_file() else title


def _used_in(models: list[str], guides: list[str]) -> list[str]:
    if not models and not guides:
        return ["## Used in", "", "No bundled model or guide uses it yet.", ""]
    lines = ["## Used in", ""]
    if models:
        lines += [f"Bundled models: {_more(models)}.", ""]
    if guides:
        lines += [f"Guides: {_more(guides)}.", ""]
    return lines


def _blocks_of(layout: dict):
    """Every block of a model, those inside its submodel definitions included."""
    yield from layout.get("blocks") or []
    for definition in (layout.get("submodels") or {}).values():
        yield from definition.get("blocks") or []


def _values_of(node, keys: tuple):
    """Every value stored under one of *keys* anywhere in *node*."""
    if isinstance(node, dict):
        for key, value in node.items():
            if key in keys:
                yield value
            yield from _values_of(value, keys)
    elif isinstance(node, list):
        for value in node:
            yield from _values_of(value, keys)


