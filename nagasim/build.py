"""Build a model in Python: a thin layer over the model JSON (D475; provisional until 1.0,
it may change between minor versions).

    from nagasim import build as nb

    m = nb.Model(time_limit=1000, warmup=100, replications=5)
    m.add_resource(name="Server")
    arrive = m.create(distribution=nb.Exponential(rate=1.0))
    serve = m.process(resource_name="Server", distribution=nb.Exponential(rate=1.25))
    arrive >> serve >> m.dispose()
    m.save("mm1.json")

Nothing here is written per block or per section. A block method (`m.process`, ...) exists
for every type in `BLOCK_REGISTRY`, plugins included, and takes its parameters by name; an
`add_<item>` method (`m.add_resource`, ...) exists for every list in
`sections.DOCUMENT_LISTS`; every other top-level section is a keyword of `Model`, and so is
every key of `simulation` (D478). A distribution constructor (`nb.Exponential(rate=...)`)
exists for every entry of `DISTRIBUTION_REGISTRY`; its object is the file's pair
`"distribution"`/`"dist_params"` (D477). The builder only writes the dict a file holds
(`m.layout`); `to_dict` is that dict in `naga fmt`'s form, `save` writes it to the path given
(the only file the builder writes) and `run` hands it to `api.run_model`. What a value means
is the engine's, as for a file.

`build.pyi` (generated by `tools/gen_engine_docs.py`) gives an editor the built-in blocks,
records, run settings and distributions; a plugin's blocks and distributions exist at run
time only.

`export_python` (`naga export --python`) writes the builder code of any model, so that
running it gives `naga fmt`'s form of the model back.
"""
from __future__ import annotations

import argparse
import inspect
import keyword
import re
import sys
from pathlib import Path

from nagasim import modelfmt
from nagasim.core import sections
from nagasim.core.block_registry import BLOCK_REGISTRY
from nagasim.core.distributions import DISTRIBUTION_REGISTRY
from nagasim.core.schema import CURRENT_VERSION
from nagasim.modelschema import build_json_schema

__all__ = ["Model", "Level", "Block", "Distribution", "export_python", "main"]

_RECORDS = {f"add_{s.item}": s for s in sections.DOCUMENT_LISTS}
_TOP = {s.name for s in sections.SECTIONS} - {"blocks", "links", "submodels"} - {
    s.name for s in sections.DOCUMENT_LISTS}
_SCHEMA = build_json_schema()
# The run settings, keywords of Model too: the keys the schema gives `simulation`.
SIMULATION = tuple(_SCHEMA["$defs"]["simulation"]["properties"])


def _record_keys(section) -> set | None:
    """The keys a record of *section* may have, from the schema; None when it is open."""
    ref = ((_SCHEMA["properties"].get(section.name) or {}).get("items") or {}).get("$ref", "")
    record = _SCHEMA["$defs"].get(ref.rsplit("/", 1)[-1]) or {}
    return set(record.get("properties") or ()) if record.get("additionalProperties") is False else None


def _keyword(name: str) -> str:
    """The Python keyword for a parameter: its name, or `lambda_` for one that is a reserved
    word (Poisson's `lambda`)."""
    return f"{name}_" if keyword.iskeyword(name) else name


class Distribution:
    """A distribution: its registry name and its parameters, as the file's `"distribution"`
    and `"dist_params"`. Made by the constructors (`nb.Exponential(rate=1.0)`); a parameter
    left out has the engine's default, as in a file."""

    __slots__ = ("name", "params")

    def __init__(self, name: str, params: dict | None = None):
        self.name, self.params = name, dict(params or {})

    def __eq__(self, other):
        return (isinstance(other, Distribution)
                and (self.name, self.params) == (other.name, other.params))

    def __repr__(self) -> str:
        # Export writes this as code: the name and the keys are registry names (checked by
        # `_as_distribution`), every value a Python literal.
        args = ", ".join(f"{_keyword(k)}={modelfmt.render(v, 4, 0, repr, 4)}"
                         for k, v in self.params.items())
        return f"nb.{self.name}({args})"


def _constructor(spec):
    names = {_keyword(p.name): p.name for p in spec.params}

    def make(**params):
        unknown = sorted(set(params) - set(names) - set(names.values()))
        if unknown:
            raise TypeError(f"{spec.name}() got unknown keyword(s) {unknown}; "
                            f"its parameters: {sorted(names)}")
        return Distribution(spec.name, {names.get(k, k): v for k, v in params.items()})

    make.__name__ = make.__qualname__ = spec.name
    make.__doc__ = "\n".join([spec.use_case, ""] + [
        f"{_keyword(p.name)}={p.default!r}: {p.hint}" for p in spec.params])
    make.__signature__ = inspect.Signature(
        [inspect.Parameter(k, inspect.Parameter.KEYWORD_ONLY, default=p.default)
         for k, p in zip(names, spec.params)])
    return make


def __getattr__(attr: str):
    """`nb.Exponential` and every other distribution of the registry, plugins' included."""
    spec = DISTRIBUTION_REGISTRY.get(attr)
    if spec is None:
        raise AttributeError(f"module {__name__!r} has no attribute {attr!r}")
    return _constructor(spec)


def __dir__():
    return sorted(set(globals()) | set(DISTRIBUTION_REGISTRY))


def _plain(value):
    """*value* as the file holds it: a Distribution given as `distribution=` becomes that
    key and `dist_params` beside it; given as any other value, the dict of the two."""
    if isinstance(value, Distribution):
        return {"distribution": value.name, "dist_params": dict(value.params)}
    if isinstance(value, list):
        return [_plain(v) for v in value]
    if not isinstance(value, dict):
        return value
    out = {}
    for key, item in value.items():
        if key == "distribution" and isinstance(item, Distribution):
            if "dist_params" in value:
                raise TypeError("distribution= is a distribution object, which holds its "
                                "parameters: give no dist_params with it")
            out["distribution"], out["dist_params"] = item.name, dict(item.params)
        else:
            out[key] = _plain(item)
    return out


class Block:
    """A block placed by a block method: its name, and `>>` to link it on."""

    __slots__ = ("level", "name")

    def __init__(self, level: "Level", name: str):
        self.level, self.name = level, name

    def __rshift__(self, other):
        return self.level.link(self, other)

    def __str__(self) -> str:
        return self.name

    def __repr__(self) -> str:
        return f"Block({self.name!r})"


def _block_method(level: "Level", spec):
    names = {p.name for p in spec.params}
    allowed = names | set(modelfmt.BLOCK_KEYS)

    def add(*args, **fields):
        # `name` is taken positionally or as `name=`; `*args` (not `name=None`) so that giving
        # both can name both values instead of Python's bare "multiple values".
        if len(args) > 1:
            raise TypeError(f"{spec.type_name.lower()}() takes at most 1 positional argument "
                            f"(the name), got {len(args)}")
        if args and "name" in fields:
            raise TypeError(f"{spec.type_name.lower()}() got the name twice: positionally "
                            f"({args[0]!r}) and as name={fields['name']!r}")
        name = args[0] if args else fields.pop("name", None)
        unknown = sorted(set(fields) - allowed)
        if unknown:
            raise TypeError(f"{spec.type_name.lower()}() got unknown keyword(s) {unknown}; "
                            f"its parameters: {sorted(names)}")
        name = name or level._next_name(spec.type_name)
        block = {"name": name, "type": spec.type_name}
        block.update({k: _plain(fields.pop(k)) for k in modelfmt.BLOCK_KEYS if k in fields})
        block["params"] = _plain(fields)
        level._data["blocks"].append(block)
        return Block(level, name)

    add.__name__ = add.__qualname__ = spec.type_name.lower()
    summary = " ".join((spec.cls.__doc__ or "").split())
    add.__doc__ = "\n".join([f"Add a {spec.type_name} block. {summary}", ""] + [
        f"{p.name}={p.default!r}{' (required)' if p.required else ''}: {p.description}"
        for p in spec.params])
    kw = inspect.Parameter.KEYWORD_ONLY
    add.__signature__ = inspect.Signature(
        [inspect.Parameter("name", inspect.Parameter.POSITIONAL_OR_KEYWORD, default=None)]
        + [inspect.Parameter(k, kw, default=None) for k in modelfmt.BLOCK_KEYS]
        + [inspect.Parameter(p.name, kw, default=p.default) for p in spec.params
           if p.name.isidentifier() and not keyword.iskeyword(p.name)])
    return add


class Level:
    """One canvas: the model's own, or a submodel definition's (`Model.definition`)."""

    def __init__(self, record: dict):
        # A (plugin) block type named like a builder method would be silently unreachable.
        hidden = sorted({t.lower() for t in BLOCK_REGISTRY} & (set(dir(type(self))) | set(_RECORDS) | {"layout"}))
        if hidden:
            raise TypeError(f"block type(s) {hidden} have the name of a builder method; "
                            "rename the plugin's block type to build with it")
        self._data = record
        record.setdefault("blocks", [])
        record.setdefault("links", [])

    def __getattr__(self, attr: str):
        spec = BLOCK_REGISTRY.get(attr.upper()) if attr.islower() else None
        if spec is None:
            raise AttributeError(f"{type(self).__name__!r} has no attribute {attr!r}")
        return _block_method(self, spec)

    def __dir__(self):
        return sorted(set(super().__dir__()) | {t.lower() for t in BLOCK_REGISTRY})

    def _next_name(self, type_name: str) -> str:
        taken = {b.get("name") for b in self._data["blocks"]}
        n = 1
        while f"{type_name.lower()}_{n}" in taken:
            n += 1
        return f"{type_name.lower()}_{n}"

    def link(self, source, target, **fields):
        """Link *source* to *target* (blocks or names); *fields* are the link's own
        (`delay`, `source_port`, `target_port`). Returns *target*, so links chain; a name
        ends a chain."""
        if any(isinstance(end, Block) and end.level is not self for end in (source, target)):
            raise ValueError(f"link {source} -> {target}: both blocks must be on this level "
                             "(a submodel definition links only its own blocks)")
        self._data["links"].append({"source": str(source), "target": str(target), **_plain(fields)})
        return target


class Model(Level):
    """A model. Keywords are the run settings (`time_limit`, `warmup`, `replications`, every
    key of `simulation`) and the top-level sections (`info`, `network`, `simulation`, ...)."""

    def __init__(self, **top):
        run = {k: top.pop(k) for k in list(top) if k in SIMULATION}
        unknown = sorted(set(top) - _TOP)
        if unknown:
            raise TypeError(f"Model() got unknown keyword(s) {unknown}; run settings: "
                            f"{list(SIMULATION)}; lists are added with {sorted(_RECORDS)}")
        if run:
            given = top.get("simulation") or {}
            both = sorted(set(run) & set(given))
            if both:
                raise TypeError(f"Model() got {both} both as a keyword and in simulation=")
            top["simulation"] = {**given, **run}
        self.layout = {"schema_version": CURRENT_VERSION, **_plain(top)}
        super().__init__(self.layout)

    def __getattr__(self, attr: str):
        section = _RECORDS.get(attr)
        if section is None:
            return super().__getattr__(attr)

        known = _record_keys(section)

        def add(**fields):
            # As a block method does (#556): a misspelt key would be written and then ignored.
            unknown = sorted(set(fields) - known) if known is not None else []
            if unknown:
                raise TypeError(f"{attr}() got unknown keyword(s) {unknown}; its keys: {sorted(known)}")
            record = _plain(fields)
            self.layout.setdefault(section.name, []).append(record)
            return record.get(section.key)

        add.__name__ = attr
        add.__doc__ = f"Add one entry to `{section.name}` and return its {section.key}. {section.doc}"
        return add

    def __dir__(self):
        return sorted(set(super().__dir__()) | set(_RECORDS))

    def definition(self, name: str, **fields) -> Level:
        """A submodel definition (`info`, `parameters`, `scoped`, ...): a Level with the same
        block methods. An instance of it is `m.submodel(definition=name, ...)`."""
        definition = _plain(fields)
        self.layout.setdefault("submodels", {})[name] = definition
        return Level(definition)

    def to_dict(self) -> dict:
        """The model in `naga fmt`'s form."""
        return modelfmt.minimal(self.layout)

    def save(self, path) -> Path:
        """Write the model to *path*, and nothing else; returns the path."""
        path = Path(path)
        path.write_text(modelfmt.dumps(self.to_dict()), encoding="utf-8", newline="\n")
        return path

    def run(self, **options):
        """`api.run_model(self.to_dict(), **options)`."""
        from nagasim import api

        return api.run_model(self.to_dict(), **options)


