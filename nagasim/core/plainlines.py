"""A problem's plain line (D1332, #1959): the short sentence a screen shows for a coded
problem, filled by code from the problem's own fields, never written by a model.

    plain(found)        the line for a Problem or its dict; its message's first clause when
                        there is none
    first(text)         a text's first sentence or the clause before a ";" (D1331)
    PLAIN               {code: template}, or {code: {case: template}} for a code whose
                        producers say different things (the problem's "case" field picks)

A template names `{block}` and the keys of the problem's `fields`; a number is shown with
`:g`. The engine's full message stays for agents and for what a screen shows on hover.
D1334: a code without a template, or a problem missing a field its template needs (one read
from an older result), shows its message's first clause, without the code or "warning: ";
the screen puts the code, the whole message and the hint on hover. A plain line is never
guessed from the message's text. `tests/test_plainlines.py` checks every producer gives the
fields its template names, and that every code a screen can show has a template.
"""
