def names_in(template: str) -> set[str]:
    """The {names} a template is filled from."""
    return set(re.findall(r"\{([a-z_]+)\}", template))


def template_for(code: str, case: str | None = None) -> str | None:
    """The template of *code* (of its *case*, for a code with several), or None."""
    said = PLAIN.get(code)
    return said.get(case or "") if isinstance(said, dict) else said


